def build_advice(ilgan: str, today_element: str, target: date, birth: date) -> dict:
    """행운 요소 + 다체계 한 줄 운세. 전부 결정적(같은 입력→같은 출력)."""
    seed = f"{birth.isoformat()}|{target.isoformat()}|{ilgan}|{today_element}"
    tips = list(TALK_TIPS)
    # 결정적 셔플 (해시 기반)
    order = sorted(range(len(tips)),
                   key=lambda i: hashlib.sha256(f"{seed}|tip{i}".encode()).hexdigest())
    talk = [tips[i] for i in order[:3]]
    avoid = str(pick(seed + "|avoid", AVOID_LIST))
    color = COLOR_BY_ELEMENT[today_element]
    number = NUMBER_BY_STEM[ilgan]
    direction = DIRECTION_BY_ELEMENT[today_element]
    time = TIME_BY_ELEMENT[today_element]
    places = PLACE_BY_ELEMENT[today_element]
    zname, planet, zvibe = zodiac_of(birth)
    lp = life_path_number(birth)
    tarot, tarot_line = pick(seed + "|tarot", TAROT_MAJOR)  # type: ignore
    omikuji, omikuji_line = pick(seed + "|omikuji", OMIKUJI)  # type: ignore
    # 주역: 6효 결정적 시뮬레이션 (노음/소양/노양/소음 → 괘명 근사)
    yao = []
    for i in range(6):
        v = int(hashlib.sha256(f"{seed}|yao{i}".encode()).hexdigest()[:4], 16) % 4
        yao.append(["노음(×)", "소양(━)", "노양(◎)", "소음(━━)"][v])
    gua, gua_line = pick(seed + "|gua", list(ICHING_MEANINGS.items()))  # type: ignore
    return {
        "color": color, "number": number, "direction": direction,
        "time": time, "places": places, "talk": talk, "avoid": avoid,
        "zodiac": {"name": zname, "planet": planet, "vibe": zvibe},
        "life_path": lp, "life_path_vibe": LIFE_PATH_VIBE[lp],
        "tarot": tarot, "tarot_line": tarot_line,
        "omikuji": omikuji, "omikuji_line": omikuji_line,
        "yao": yao, "gua": gua, "gua_line": gua_line,
    }
