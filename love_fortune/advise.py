def pick(seed: str, pool: list) -> object:
    h = hashlib.sha256(seed.encode("utf-8")).hexdigest()
    return pool[int(h[:8], 16) % len(pool)]


def zodiac_of(birth: date) -> tuple[str, str, str]:
    m, d = birth.month, birth.day
    for (sm, sd), (em, ed), name, planet, vibe in ZODIAC:
        if (sm, sd) <= (em, ed):  # 연도 안 넘김
            if (sm, sd) <= (m, d) <= (em, ed):
                return name, planet, vibe
        else:  # 염소자리처럼 연도 경계 넘김
            if (m, d) >= (sm, sd) or (m, d) <= (em, ed):
                return name, planet, vibe
    return "물고기자리", "해왕성", "감성적인 공감 표현이 통하기 쉬운 흐름"


