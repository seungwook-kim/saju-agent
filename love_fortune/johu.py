def name(stem: str) -> str:
    return stem + ELEMENT[stem]


def lookup(day_stem: str, month_branch: str) -> list[str]:
    return list(TABLE[day_stem][MONTHS.index(month_branch)])


def analyze(ds: int, month_branch: int, stems: list[int], strong: bool) -> dict:
    """일간(번호)·월지(번호)·원국 천간(번호)·억부 신강 여부 → 조후용신 풀이. 개인정보 없음."""
    me, mb = STEMS[ds], BRANCHES[month_branch]
    order = lookup(me, mb)
    main = order[:2]
    groups = [GROUP[ten_god(ds, STEMS.index(s))] for s in main]
    eokbu = {"관성", "식상", "재성"} if strong else {"인성", "비겁"}
    agree = groups[0] in eokbu
    have = [s for s in main if STEMS.index(s) in stems]
    return {"order": order, "main": main, "groups": groups, "agree": agree, "have": have,
            "extreme": mb in EXTREME, "text": _text(me, mb, main, groups, agree, have, mb in EXTREME, strong)}


def _text(me, mb, main, groups, agree, have, extreme, strong) -> list[str]:
    first = f"{name(main[0])}({IMAGE[main[0]]}, {GROUP_PLAIN[groups[0]]})"
    lines = [f"계절로 보면 {SEASON[mb]} {mb}월에 태어난 {j(f'{name(me)}({IMAGE[me]})', '이야')}. "
             f"궁통보감(청나라 때 정리된 계절별 용신 고전)은 이럴 때 {j(first, '을')} "
             + (f"먼저 꼽고, 그다음은 {j(f'{name(main[1])}({IMAGE[main[1]]})', '이야')}." if len(main) > 1 else "꼽아.")]
    eok = "나를 받쳐 주고 같은 편이 되는 기운" if not strong else "힘을 빼고 다스리는 기운"
    if agree:
        lines.append(f"힘의 세기로 고른 용신(억부)도 {eok} 쪽이라, 두 방법이 같은 쪽을 가리켜. 그만큼 이 기운이 반가운 사주야.")
    else:
        lines.append(f"힘의 세기로 고른 용신(억부)은 {eok} 쪽이라 계절로 고른 것과 달라. "
                     + ("덥거나 추운 게 뚜렷한 달에 태어났으니 궁통보감은 계절 맞추기를 먼저 챙기라고 봐."
                        if extreme else "봄·가을생은 춥고 더운 게 덜해서 힘의 세기 쪽도 함께 무겁게 봐."))
    if have:
        lines.append(f"원국 하늘 글자에 {j('·'.join(name(s) for s in have), '이')} 이미 떠 있어서 계절 균형을 스스로 조금 갖춘 편이야.")
    else:
        lines.append(f"원국 하늘 글자에는 {j(name(main[0]), '이')} 없어서, 대운이나 한 해 운에서 들어올 때 반가운 기운이야.")
    return lines

