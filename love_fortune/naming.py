def split_syllable(ch: str) -> tuple[str, str, str] | None:
    code = ord(ch) - 0xAC00
    if not 0 <= code < 11172:
        return None
    return CHO[code // 588], JUNG[(code % 588) // 28], str(code % 28)


def relation(a: str, b: str) -> str:
    if a == b:
        return "same"
    if GEN[a] == b or GEN[b] == a:
        return "gen"
    return "ke"


