        outer = "장외도화(사적 매력)" if any(a in ("일지", "시지") for a in at) else ""
        dh_lines.append(f"도화({BRANCHES_KR[ch]})가 {', '.join(at)}에, "
                        + "·".join(x for x in (inner, outer) if x) + f" / {DOHWA_CHARM[ch]}")
