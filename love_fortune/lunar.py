def _new_year(ly: int) -> date:
    mmdd = LUNAR[ly][0]
    return date(ly, mmdd // 100, mmdd % 100)


def solar_to_lunar(y: int, m: int, d: int) -> tuple[int, int, int, bool]:
    """양력 → 음력 (년, 월, 일, 윤달여부)."""
    if not (MIN_YEAR <= y <= MAX_YEAR):
        raise ValueError(f"지원 범위 초과: {MIN_YEAR}–{MAX_YEAR}년")
    dt = date(y, m, d)
    ly = y
    ny = _new_year(ly)
    if dt < ny:
        ly -= 1
        ny = _new_year(ly)
    offset = (dt - ny).days
    leap, mask, leap_len = LUNAR[ly][1], LUNAR[ly][2], LUNAR[ly][3]
    ml = 1
    while True:
        ln = 30 if (mask >> (12 - ml)) & 1 else 29
        if offset < ln:
            return (ly, ml, offset + 1, False)
        offset -= ln
        if ml == leap:
            if offset < leap_len:
                return (ly, ml, offset + 1, True)
            offset -= leap_len
        ml += 1
        if ml > 12:
            raise RuntimeError("음력 변환 실패")


