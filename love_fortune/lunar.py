def lookup_city(city: str) -> tuple[float, float, bool]:
    """(경도, 위도, 매칭여부). 못 찾으면 127.0(대전 근방)."""
    if city in CITY_GEO:
        lon, lat = CITY_GEO[city]
        return lon, lat, True
    for name, (lon, lat) in CITY_GEO.items():
        if name in city or city in name:
            return lon, lat, True
    return 127.0, 36.4, False


def true_solar_time(y: int, m: int, d: int, hh: int, mm: int,
                    city: str) -> tuple[datetime, float, float, bool]:
    """KST 입력 → 진태양시(datetime). (시각, 보정분, 사용경도, 도시매칭)."""
    lon, _lat, matched = lookup_city(city)
    kst = datetime(y, m, d, hh, mm)
    corr = -(135.0 - lon) * 4.0 + equation_of_time(kst.date())
    return kst + timedelta(minutes=corr), corr, lon, matched
